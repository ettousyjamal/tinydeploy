"""Self-contained example run that exercises every pipeline stage.

``run_demo`` executes three parts and writes every input, log and result:

1. ``selection`` - three candidates against a small target: budget filtering,
   rejection reasons, Pareto set and C header.
2. ``grid``      - Algorithm 1 on the 2 x 4 grid (bit-width {8, 4} x pruning
   {0, 0.3, 0.5, 0.7}); INT4 is skipped as unsupported on the target, and
   compression/profiling run as logged external commands.
3. ``ota``       - a 500-device, three-round A/B fleet simulation comparing
   full-image and delta updates.

The example uses small generated byte strings in place of real models and
firmware, and its profiles carry ``provenance.kind = "synthetic"``. It shows
how the software behaves; it does not reproduce any result of the paper. Real
runs use trained models and Edge Impulse or on-board measurements imported with
:mod:`tinydeploy.profiles`.
"""

from __future__ import annotations

import random
import sys
from pathlib import Path
from typing import Any

from ._util import digest, read_json, write_json
from .grid import PAPER_BIT_WIDTHS, PAPER_PRUNE_RATIOS
from .ota import simulate
from .selection import run

# Deterministic outcome of the example run, used as a regression reference.
